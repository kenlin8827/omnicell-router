    const d = dragRef.current;
    if (!d || d.tier !== tier) return;
    const container = listRefs.current[tier];
    if (!container) return;
    // Edge auto-scroll: riding the top/bottom fold of the internal scroll
    // area keeps long pools reachable while dragging.
