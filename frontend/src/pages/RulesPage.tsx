/** One member rule row. `effortMap` values: '' / missing = passthrough. */
interface MemberRow {
  pattern: string;
  weight?: number; // ≥ 1; undefined = 1 (orders priority too: weight desc, then list order)
  effortMap: Record<string, string>;
}

