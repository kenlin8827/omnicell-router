/**
 * PAC (proxy auto-config) generator for the mihomo outbound core (ADR-0022).
 *
 * Why PAC: a browser or a client that only understands "point me at a proxy
 * config URL" cannot be handed an HTTP/SOCKS port and a bypass list. A PAC
 * script carries BOTH — the mixed port to use and the hosts that must stay
 * direct — in one URL, and the client re-reads it on demand, so the port in the
 * console stays the single source of truth.
 *
 * The bypass list is the PAC-side mirror of the router's own loopback rule
 * (`isLoopbackHost` in ../forward-proxy/rules.ts): anything that cannot leave
 * the machine, or that belongs to the local network, is DIRECT. Keeping those
 * requests off the core also keeps them off the console's own control port.
 *
 * What is deliberately NOT mirrored: `proxy.includes` / `proxy.excludes` match
 * provider/model names, not hosts, so they have no meaning in a PAC script.
 */

/** Served at the gateway root, outside /api (browsers fetch it unauthenticated). */
export const PAC_PATH = '/proxy.pac';

export interface PacScriptOptions {
  /** The mihomo mixed port (HTTP + SOCKS5 on one listener). */
  proxyPort: number;
  /** Host the core listens on; the core only ever binds loopback. */
  proxyHost?: string;
}

/** RFC1918 / link-local / CGNAT ranges, spelled for `shExpMatch`. */
const PRIVATE_RANGES: readonly string[] = [
  '10.*',
  '172.16.*',
  '172.17.*',
  '172.18.*',
  '172.19.*',
  '172.20.*',
  '172.21.*',
  '172.22.*',
  '172.23.*',
  '172.24.*',
  '172.25.*',
  '172.26.*',
  '172.27.*',
  '172.28.*',
  '172.29.*',
  '172.30.*',
  '172.31.*',
  '192.168.*',
  '169.254.*',
  '100.64.*',
  '127.*',
  '0.*',
];

export function buildPacScript({ proxyPort, proxyHost = '127.0.0.1' }: PacScriptOptions): string {
  const proxy = `PROXY ${proxyHost}:${proxyPort}`;
  const rules = PRIVATE_RANGES.map((range) => `  if (shExpMatch(host, '${range}')) return 'DIRECT';`).join('\n');
  return `// Generated by OmniCellRouter — mihomo (Clash) mixed port ${proxyPort}.
// Loopback, link-local, private and mDNS names stay direct so local services are
// never routed through the core. Everything else goes to the mixed port.
function FindProxyForURL(url, host) {
  if (isPlainHostName(host)) return 'DIRECT';
  if (host === 'localhost' || host === '::1' || host === '[::1]') return 'DIRECT';
  if (dnsDomainIs(host, '.localhost')) return 'DIRECT';
  if (shExpMatch(host, '*.local')) return 'DIRECT';
${rules}
  return '${proxy}';
}
`;
}
