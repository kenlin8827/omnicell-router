/**
 * Bidirectional reconciliation:
 * 1. Discover native marketplaces from local agents and import them into OCR.
 * 2. Push all enabled OCR marketplaces to native host agents.
 */
export async function reconcileMarketplaces(
  hosts?: HarnessHostId[],
  fetchImpl?: typeof fetch,
  execImpl?: ExecImpl,
): Promise<MarketplaceReconciliationReport> {
  // Step 1: Discover & Ingress
  const discovered = await discoverNativeMarketplaces(hosts);
  const { imported } = await importNativeMarketplacesToOcr({ hosts, fetchImpl });

  // Step 2: Egress & Sync down enabled OCR marketplaces
  const currentEntries = (hosts && hosts.length === 1
    ? listMarketplaceEntries(hosts[0])
    : listMarketplaceEntries()
  ).filter((e) => e.enabled);
  const syncResults: MarketplaceSyncResult[] = [];

  for (const entry of currentEntries) {
    const resList = await syncMarketplaceToHost(entry, execImpl);
    syncResults.push(...resList);
  }

  const failedCount = syncResults.filter((r) => !r.ok).length;

  return {
    timestamp: Date.now(),
    discovered,
    imported: imported.map((e) => ({ slug: e.slug, repo: e.repo, harness: e.harness ?? undefined })),
    synced: syncResults,
    summary: {
      discoveredCount: discovered.length,
      importedCount: imported.length,
      syncedCount: syncResults.length,
      failedCount,
    },
  };
}
