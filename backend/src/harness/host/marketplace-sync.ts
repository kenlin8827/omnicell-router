import { HOST_ADAPTERS, adapterFor } from './adapters/index.js';
import type { NativeMarketplaceInfo, MarketplaceSyncResult, BaseHostAdapter } from './adapters/base.js';
import {
  listMarketplaceEntries,
  addMarketplaceEntry,
  resolveSlug,
  probeMarketplace,
  type MarketplaceEntry,
} from '../common/market.js';
import { harvestIndex, harvestAll } from '../plugin/catalog.js';
import type { ExecImpl } from './writers/plugin.js';
import type { HarnessHostId } from '../types.js';

export interface ExtendedNativeMarketplaceInfo extends NativeMarketplaceInfo {
  host?: HarnessHostId;
}

/**
 * Report generated by bidirectional marketplace synchronization.
 */
export interface MarketplaceReconciliationReport {
  timestamp: number;
  discovered: ExtendedNativeMarketplaceInfo[];
  imported: { slug: string; repo: string; harness?: HarnessHostId }[];
  synced: MarketplaceSyncResult[];
  summary: {
    discoveredCount: number;
    importedCount: number;
    syncedCount: number;
    failedCount: number;
  };
}

/**
 * Discover all native marketplaces configured in local agent environments.
 */
export async function discoverNativeMarketplaces(hosts?: HarnessHostId[]): Promise<ExtendedNativeMarketplaceInfo[]> {
  const targets = hosts
    ? hosts.map((h) => adapterFor(h)).filter((a): a is BaseHostAdapter => a instanceof Object)
    : (HOST_ADAPTERS as readonly BaseHostAdapter[]);

  const results: ExtendedNativeMarketplaceInfo[] = [];

  for (const adapter of targets) {
    if (typeof adapter.listNativeMarketplaces !== 'function') continue;
    try {
      const found = await adapter.listNativeMarketplaces();
      for (const item of found) {
        results.push({
          ...item,
          host: adapter.id,
        });
      }
    } catch {
      // ignore discovery failures for unavailable agents
    }
  }

  return results;
}

/**
 * Import discovered native marketplaces into OCR's store, scoped to the discovering harness.
 * The duplicate answer is `resolveSlug`'s alone — store-wide, because one slug is one `mp-` id —
 * so a repository already carried under any scope is skipped, never twinned.
 */
export async function importNativeMarketplacesToOcr(options: {
  hosts?: HarnessHostId[];
  fetchImpl?: typeof fetch;
} = {}): Promise<{ imported: MarketplaceEntry[]; skipped: string[] }> {
  const discovered = await discoverNativeMarketplaces(options.hosts);
  const imported: MarketplaceEntry[] = [];
  const skipped: string[] = [];

  for (const item of discovered) {
    const host = item.host;

    const resolved = resolveSlug(item.repo, null);
    if (!resolved.ok) {
      skipped.push(`${host ?? 'any'}:${item.repo}`);
      continue;
    }

    try {
      const entry = addMarketplaceEntry({
        slug: resolved.slug,
        repo: item.repo,
        type: item.type ?? 'github',
        rescan: { enabled: false, intervalMs: 86_400_000 },
        harness: host ?? null,
      });

      // Best-effort background probe
      void import('../plugin/adapters/index.js').then(({ allHostProbes, probeOptionsFor }) => {
        return probeMarketplace(entry, options.fetchImpl, {
          ...probeOptionsFor(host ?? null),
          hosts: allHostProbes(),
        }).then(() => {
          if (host) {
            harvestIndex(host);
          } else {
            harvestAll();
          }
        });
      });

      imported.push(entry);
    } catch {
      skipped.push(`${host ?? 'any'}:${item.repo}`);
    }
  }

  if (imported.length > 0) {
    if (options.hosts && options.hosts.length === 1) {
      harvestIndex(options.hosts[0]);
    } else {
      harvestAll();
    }
  }

  return { imported, skipped };
}

/**
 * Sync an OCR marketplace down to its owning host agent (or all hosts if harness is unset).
 */
export async function syncMarketplaceToHost(
  entry: MarketplaceEntry,
  execImpl?: ExecImpl,
): Promise<MarketplaceSyncResult[]> {
  if (entry.harness) {
    const adapter = adapterFor(entry.harness) as BaseHostAdapter | undefined;
    if (!adapter || typeof adapter.syncMarketplaceToHost !== 'function') return [];
    try {
      const res = await adapter.syncMarketplaceToHost(entry, execImpl);
      return res.action !== 'skipped' ? [res] : [];
    } catch (e) {
      return [{
        host: adapter.id,
        action: 'add',
        repo: entry.repo,
        ok: false,
        error: e instanceof Error ? e.message : String(e),
      }];
    }
  }
  return syncMarketplaceToAllHosts(entry, execImpl);
}

/**
 * Sync an OCR marketplace down to all native host agents that support marketplace registration.
 */
export async function syncMarketplaceToAllHosts(
  entry: MarketplaceEntry,
  execImpl?: ExecImpl,
): Promise<MarketplaceSyncResult[]> {
  const results: MarketplaceSyncResult[] = [];
  const targets = entry.harness
    ? [adapterFor(entry.harness)].filter((a): a is BaseHostAdapter => a instanceof Object)
    : (HOST_ADAPTERS as readonly BaseHostAdapter[]);

  for (const adapter of targets) {
    if (typeof adapter.syncMarketplaceToHost !== 'function') continue;
    try {
      const res = await adapter.syncMarketplaceToHost(entry, execImpl);
      if (res.action !== 'skipped') {
        results.push(res);
      }
    } catch (e) {
      results.push({
        host: adapter.id,
        action: 'add',
        repo: entry.repo,
        ok: false,
        error: e instanceof Error ? e.message : String(e),
      });
    }
  }
  return results;
}

